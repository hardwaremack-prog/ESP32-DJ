#!/usr/bin/env python3
"""Gzip web/index.html into firmware/ESP32DJ/src/webui.h (run before compiling)."""
import gzip, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "web" / "index.html").read_bytes()
gz = gzip.compress(html, 9, mtime=0)
out = root / "firmware" / "ESP32DJ" / "src" / "webui.h"
lines = ["// generated by tools/embed_webui.py - do not edit", "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
         f"static const size_t WEBUI_GZ_LEN = {len(gz)};", "static const uint8_t WEBUI_GZ[] = {"]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(str(b) for b in gz[i:i+20]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"webui.h: {len(html)} bytes html -> {len(gz)} bytes gzip")
